    raw.update(c1519.CATALOG_2015_2019)
    raw.update(c1729.CATALOG_2017_2019)
    raw.update(c2025.CATALOG_2020_2025)

    # 2019: extend pool
    append_unique(raw[2019], SPARE_2019, finalize(raw, 2018)[1])
    raw[2019] = dedupe_pool(raw[2019])

    # 2020: replace with filtered spare-only build
    _, seen19 = finalize(raw, 2019)
    pool20: list = []
    append_unique(pool20, SPARE_2020, seen19)
    raw[2020] = dedupe_pool(pool20)

    # 2021-2024: extend
    for year in range(2021, 2025):
        _, seen = finalize(raw, year - 1)
        append_unique(raw[year], SPARE_BY_YEAR[year], seen)
        raw[year] = dedupe_pool(raw[year])

    # Fix known issues in existing pools
    raw[2021] = [(a, t, al) for a, t, al in raw[2021] if not (a == "TREASURE" and t == "JIKJIN")]
