def rebuild_pool(raw: dict, year: int, primary: list, spare: list) -> list:
    _, seen = finalize(raw, year - 1)
    pool = dedupe_pool(list(primary))
    append_unique(pool, spare, seen)
    # filter pool order: keep only globally unique vs prior years
    filtered: list[tuple[str, str, str]] = []
    for artist, title, album in pool:
        if track_key(artist, title) not in seen:
            filtered.append((artist, title, album))
    return filtered


