#!/usr/bin/env python3
"""Fix under-filled year pools by filtering against global selections and adding spares."""
from __future__ import annotations

import importlib.util
import re
import unicodedata
from collections import Counter
from pathlib import Path

GEN = Path(__file__).parent
MAX_PER = 2
TARGET = 100


def track_key(artist: str, title: str) -> str:
    def norm(s: str) -> str:
        s = unicodedata.normalize("NFKC", s or "").lower().replace("&", " and ")
        s = re.sub(r"\bfeat\.?\b|\bft\.?\b|\bfeaturing\b", " ", s)
        s = re.sub(r"[^\w\s가-힣]+", " ", s, flags=re.UNICODE)
        return re.sub(r"\s+", " ", s).strip()

    return f"{norm(artist)}|{norm(title)}"


def load(path: Path):
    spec = importlib.util.spec_from_file_location(path.stem, path)
    mod = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(mod)
    return mod


def finalize(raw: dict[int, list], upto: int) -> tuple[dict[int, list], set[str]]:
    seen: set[str] = set()
    out: dict[int, list] = {}
    for year in range(2015, upto + 1):
        pool = raw.get(year, [])
        result: list[tuple[str, str, str]] = []
        ac: Counter[str] = Counter()
        for artist, title, album in pool:
            if len(result) >= TARGET:
                break
            if ac[artist] >= MAX_PER:
                continue
            k = track_key(artist, title)
            if k in seen:
                continue
            result.append((artist, title, album))
            ac[artist] += 1
            seen.add(k)
        out[year] = result
    return out, seen


def dedupe_pool(pool: list[tuple[str, str, str]]) -> list[tuple[str, str, str]]:
    seen: set[tuple[str, str]] = set()
    out: list[tuple[str, str, str]] = []
    for t in pool:
        k = (t[0], t[1])
        if k in seen:
            continue
        seen.add(k)
        out.append(t)
    return out


def append_unique(pool: list, extras: list, global_seen: set[str]) -> None:
    have = {(a, b) for a, b, _ in pool}
    for artist, title, album in extras:
        k = track_key(artist, title)
        if (artist, title) in have or k in global_seen:
            continue
        pool.append((artist, title, album))
        have.add((artist, title))


