CREATE INDEX nrm_alarm_alarm_date_idx ON public.nrm_alarm (alarm_date DESC);
CREATE INDEX nrm_alarm_serial_no_idx ON public.nrm_alarm (serial_no);

CREATE TRIGGER nrm_alarm_updated_at
  BEFORE UPDATE ON public.nrm_alarm
