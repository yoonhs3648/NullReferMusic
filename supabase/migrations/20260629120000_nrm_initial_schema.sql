-- ── 공통 ─────────────────────────────────────────────────────────────────────
CREATE OR REPLACE FUNCTION public.nrm_set_updated_at()
RETURNS TRIGGER
LANGUAGE plpgsql
AS $$
BEGIN
  NEW.updated_at = now();
  RETURN NEW;
END;
$$;

-- ── nrm_apk_version (data/apkVersion.json) ───────────────────────────────────
CREATE TABLE public.nrm_apk_version (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  version TEXT NOT NULL,
  created_date TIMESTAMPTZ NOT NULL,
  inserted_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  CONSTRAINT nrm_apk_version_version_unique UNIQUE (version)
);

CREATE INDEX nrm_apk_version_created_date_idx
  ON public.nrm_apk_version (created_date DESC);

CREATE TRIGGER nrm_apk_version_updated_at
  BEFORE UPDATE ON public.nrm_apk_version
  FOR EACH ROW EXECUTE FUNCTION public.nrm_set_updated_at();

COMMENT ON TABLE public.nrm_apk_version IS 'GitHub Releases 공개 APK 최신 버전 (구 data/apkVersion.json). 최신 1건: ORDER BY created_date DESC, id DESC LIMIT 1';

-- ── nrm_alarm (data/alarm.json) ──────────────────────────────────────────────
