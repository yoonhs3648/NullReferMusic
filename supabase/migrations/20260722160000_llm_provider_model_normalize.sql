DROP FUNCTION IF EXISTS public.nrm_rpc_chat_finalize_turn(bigint, varchar, text, integer, integer, integer, text, bigint, boolean, boolean);

CREATE OR REPLACE FUNCTION public.nrm_rpc_chat_finalize_turn(
  p_session_id bigint,
  p_role varchar,
  p_content text,
  p_input_token integer,
  p_output_token integer,
  p_total_token integer,
  p_serial_no text,
  p_provider_id bigint,
  p_model_id bigint,
  p_record_history boolean,
  p_is_success boolean
)
RETURNS jsonb
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
DECLARE
  v_msg public."ChatMessage"%ROWTYPE;
BEGIN
  INSERT INTO public."ChatMessage" ("SessionID", "Role", "Content", "InputToken", "OutputToken", "TotalToken")
  VALUES (
    p_session_id,
    p_role,
    p_content,
    coalesce(p_input_token, 0),
    coalesce(p_output_token, 0),
    coalesce(p_total_token, 0)
  )
  RETURNING * INTO v_msg;

  UPDATE public."ChatSession" SET "UpdateDate" = now() WHERE "SessionID" = p_session_id;

  IF p_record_history THEN
    INSERT INTO public."LLMTokenHistory" ("SerialNo", "ProviderID", "ModelID", "InputToken", "OutputToken", "TotalToken", "isSuccess")
    VALUES (
      p_serial_no,
      p_provider_id,
      p_model_id,
      coalesce(p_input_token, 0),
      coalesce(p_output_token, 0),
      coalesce(p_total_token, 0),
      p_is_success
    );
  END IF;

  RETURN to_jsonb(v_msg);
END;
$$;

