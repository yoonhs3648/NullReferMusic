-- ── 6) LLMUserPermission: 모델 단위 → provider 단위로 합치기 ─────────────────────────
-- 기존 "ProviderID"는 사실 모델 ID였다(구 LLMModel.ModelID와 동일 값) — LLMModel을
-- join해 실제 provider ID로 사상하고, 동일 (SerialNo, provider) 조합으로 GROUP BY해
-- 하나로 합친다. 승인 여부는 OR(하나라도 승인돼 있었으면 승인), 할당 토큰은
-- "무제한(0)이 하나라도 있으면 무제한, 아니면 그중 최댓값"으로 합친다.

CREATE TEMP TABLE tmp_llm_user_permission_v2 AS
SELECT
  p."SerialNo",
  lm."ProviderID",
  bool_or(p."IsApproved") AS "IsApproved",
  CASE WHEN bool_or(p."AllocatedToken" = 0) THEN 0 ELSE max(p."AllocatedToken") END AS "AllocatedToken",
  max(p."ApprovedDate") AS "ApprovedDate",
  min(p."RegDate") AS "RegDate"
FROM public."LLMUserPermission" p
JOIN public."LLMModel" lm ON lm."ModelID" = p."ProviderID"
GROUP BY p."SerialNo", lm."ProviderID";

TRUNCATE public."LLMUserPermission" RESTART IDENTITY;

INSERT INTO public."LLMUserPermission"
  ("SerialNo", "ProviderID", "IsApproved", "AllocatedToken", "ApprovedDate", "RegDate", "UpdateDate")
SELECT
  "SerialNo", "ProviderID", "IsApproved", "AllocatedToken", "ApprovedDate", coalesce("RegDate", now()), now()
FROM tmp_llm_user_permission_v2;

DROP TABLE tmp_llm_user_permission_v2;

COMMENT ON COLUMN public."LLMUserPermission"."ProviderID"
IS 'LLM 제공자 고유번호 (LLMProvider.ProviderID) — 모델 단위가 아니라 제공자 단위 승인/할당';

-- ── 7) LLMUserMonthlyAllocation: 모델 단위 → provider 단위로 합치기 ──────────────────

CREATE TEMP TABLE tmp_llm_alloc_v2 AS
SELECT
  a."SerialNo",
  lm."ProviderID",
  a."TargetMonth",
  CASE WHEN bool_or(a."AllocatedToken" = 0) THEN 0 ELSE max(a."AllocatedToken") END AS "AllocatedToken",
  max(a."UpdatedBySerialNo") AS "UpdatedBySerialNo",
  min(a."RegDate") AS "RegDate",
  max(a."UpdateDate") AS "UpdateDate"
FROM public."LLMUserMonthlyAllocation" a
JOIN public."LLMModel" lm ON lm."ModelID" = a."ProviderID"
GROUP BY a."SerialNo", lm."ProviderID", a."TargetMonth";

TRUNCATE public."LLMUserMonthlyAllocation" RESTART IDENTITY;

INSERT INTO public."LLMUserMonthlyAllocation"
  ("SerialNo", "ProviderID", "TargetMonth", "AllocatedToken", "UpdatedBySerialNo", "RegDate", "UpdateDate")
SELECT
  "SerialNo", "ProviderID", "TargetMonth", "AllocatedToken", "UpdatedBySerialNo",
  coalesce("RegDate", now()), coalesce("UpdateDate", now())
FROM tmp_llm_alloc_v2;

DROP TABLE tmp_llm_alloc_v2;

COMMENT ON COLUMN public."LLMUserMonthlyAllocation"."ProviderID"
IS 'LLM 제공자 고유번호 (LLMProvider.ProviderID) — 모델 단위가 아니라 제공자 단위 할당';

-- ── 8) LLMUserQuota: 모델 단위 → provider 단위로 합치기(토큰은 SUM) ──────────────────
-- 요구사항: 이 테이블은 (SerialNo, TargetMonth) 조합이 구조적으로 유일해야 한다
-- (제공자가 하나뿐인 지금은 결과적으로 동일). 기존에 모델별로 나뉘어 있던 행들을
-- provider 단위로 합치면서 토큰 사용량은 SUM한다.

CREATE TEMP TABLE tmp_llm_quota_v2 AS
SELECT
  q."SerialNo",
  lm."ProviderID",
  q."TargetMonth",
  sum(q."InputToken") AS "InputToken",
  sum(q."OutputToken") AS "OutputToken",
  sum(q."TotalToken") AS "TotalToken",
  min(q."RegDate") AS "RegDate",
  max(q."UpdateDate") AS "UpdateDate"
FROM public."LLMUserQuota" q
JOIN public."LLMModel" lm ON lm."ModelID" = q."ProviderID"
GROUP BY q."SerialNo", lm."ProviderID", q."TargetMonth";

TRUNCATE public."LLMUserQuota" RESTART IDENTITY;

INSERT INTO public."LLMUserQuota"
  ("SerialNo", "ProviderID", "TargetMonth", "InputToken", "OutputToken", "TotalToken", "RegDate", "UpdateDate")
SELECT
  "SerialNo", "ProviderID", "TargetMonth", "InputToken", "OutputToken", "TotalToken",
  coalesce("RegDate", now()), coalesce("UpdateDate", now())
FROM tmp_llm_quota_v2;

DROP TABLE tmp_llm_quota_v2;

COMMENT ON COLUMN public."LLMUserQuota"."ProviderID"
IS 'LLM 제공자 고유번호 (LLMProvider.ProviderID) — 모델 단위가 아니라 제공자 단위 누적. (SerialNo, TargetMonth) 조합은 항상 유일';

-- ── 9) 관리자 RPC: 모델 시드는 이제 LLMModel 대상 + ProviderID 필요 ──────────────────

DROP FUNCTION IF EXISTS public.nrm_rpc_admin_replace_llm_providers(text, jsonb);

CREATE OR REPLACE FUNCTION public.nrm_rpc_admin_replace_llm_models(
  p_caller_serial text,
  p_rows jsonb
)
RETURNS integer
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
DECLARE
  v_row jsonb;
  v_count integer := 0;
BEGIN
  IF NOT public.nrm_is_admin_caller(p_caller_serial) THEN
    RAISE EXCEPTION 'admin required';
  END IF;

  DELETE FROM public."LLMModel";

  FOR v_row IN SELECT * FROM jsonb_array_elements(p_rows)
  LOOP
    INSERT INTO public."LLMModel" (
      "ProviderID",
      "Type",
      "ModelName",
      "ModelDisplayName",
      "Version",
      "Description",
      "IsActive"
    )
    VALUES (
      (v_row->>'ProviderID')::bigint,
      v_row->>'Type',
      v_row->>'ModelName',
      v_row->>'ModelDisplayName',
      v_row->>'Version',
      NULLIF(v_row->>'Description', ''),
      COALESCE((v_row->>'IsActive')::boolean, false)
    );
    v_count := v_count + 1;
  END LOOP;

  RETURN v_count;
END;
$$;

COMMENT ON FUNCTION public.nrm_rpc_admin_replace_llm_models(text, jsonb)
IS 'admin: LLMModel 전체 교체 시드 (Gemini 모델 목록 등, 각 row는 ProviderID를 포함해야 함)';

GRANT EXECUTE ON FUNCTION public.nrm_rpc_admin_replace_llm_models(text, jsonb)
TO anon, authenticated;

-- ── 10) nrm_rpc_chat_prepare_turn: 모델 단위 파라미터/조회로 재작성 ──────────────────
-- 변경점:
--   - p_provider_id → p_model_id (앱이 실제로 고르는 건 "모델").
--   - LLMModel + LLMProvider를 join해 apiKey/providerName 등을 얻는다.
--   - 기존 세션을 이어받는 경우(p_session_id) 그 세션에 저장된 ModelID/ProviderID를
--     "그대로" 사용한다(클라이언트가 p_model_id를 잘못 보내도 세션의 원래 모델로
--     계속 요청되도록 서버가 최종 보정 — 요구사항: "해당 채팅세션에서는 해당 모델로
--     계속 요청할 수 있게").
--   - LLMProvider에 DailyLimit/MonthlyLimit 컬럼이 더 이상 없으므로, 제공자 단위
--     일일/월간 전체 사용자 합산 한도 체크(20260721140000에서 추가됐던 로직)는
--     완전히 제거한다.

-- Postgres는 CREATE OR REPLACE로 파라미터 "이름"만 바꾸는 것을 허용하지 않는다
-- (타입/개수가 같아도 "cannot change name of input parameter" 에러) — 명시적으로
-- 기존 시그니처를 먼저 지운다.
DROP FUNCTION IF EXISTS public.nrm_rpc_chat_prepare_turn(text, bigint, bigint, text, varchar, integer);

CREATE OR REPLACE FUNCTION public.nrm_rpc_chat_prepare_turn(
  p_serial_no text,
  p_model_id bigint,
  p_session_id bigint,
  p_content text,
  p_target_month varchar,
  p_history_limit integer DEFAULT 40
)
RETURNS jsonb
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
DECLARE
  v_session_id bigint;
  v_is_new boolean := false;
  v_clean text;
  v_title varchar;
  v_user_msg public."ChatMessage"%ROWTYPE;
  v_session_provider_id bigint;
  v_session_model_id bigint;
  v_effective_model_id bigint;
  v_model_id bigint;
  v_provider_id bigint;
  v_provider_name varchar;
  v_model_name varchar;
  v_model_display_name text;
  v_api_key text;
  v_is_active boolean;
  v_is_approved boolean;
  v_allocated_token bigint;
  v_quota_used bigint;
  v_history jsonb;
BEGIN
  IF p_session_id IS NOT NULL THEN
    SELECT "SessionID", "Title", "ProviderID", "ModelID"
    INTO v_session_id, v_title, v_session_provider_id, v_session_model_id
    FROM public."ChatSession"
    WHERE "SessionID" = p_session_id AND "SerialNo" = p_serial_no AND "IsDeleted" = false;
  END IF;

  -- 기존 세션이면 그 세션의 모델을 최종 사용(클라이언트 값보다 우선). 새 세션이면
  -- 클라이언트가 고른 모델을 그대로 쓴다.
  v_effective_model_id := COALESCE(v_session_model_id, p_model_id);

  IF v_session_id IS NULL THEN
    v_clean := trim(regexp_replace(coalesce(p_content, ''), '\s+', ' ', 'g'));
    IF v_clean = '' THEN
      v_title := '새 대화';
    ELSIF length(v_clean) > 28 THEN
      v_title := left(v_clean, 28) || '…';
    ELSE
      v_title := v_clean;
    END IF;

    SELECT "ProviderID" INTO v_provider_id FROM public."LLMModel" WHERE "ModelID" = v_effective_model_id;

    INSERT INTO public."ChatSession" ("SerialNo", "ProviderID", "ModelID", "Title")
    VALUES (p_serial_no, v_provider_id, v_effective_model_id, v_title)
    RETURNING "SessionID" INTO v_session_id;
    v_is_new := true;
  END IF;

  INSERT INTO public."ChatMessage" ("SessionID", "Role", "Content")
  VALUES (v_session_id, p_serial_no, p_content)
  RETURNING * INTO v_user_msg;

  UPDATE public."ChatSession" SET "UpdateDate" = now() WHERE "SessionID" = v_session_id;

  SELECT lm."ModelID", lm."ProviderID", lm."ModelName", lm."ModelDisplayName", lm."IsActive",
         lp."ProviderName", lp."ApiKey"
  INTO v_model_id, v_provider_id, v_model_name, v_model_display_name, v_is_active,
       v_provider_name, v_api_key
  FROM public."LLMModel" lm
  JOIN public."LLMProvider" lp ON lp."ProviderID" = lm."ProviderID"
  WHERE lm."ModelID" = v_effective_model_id;

  SELECT "IsApproved", "AllocatedToken"
  INTO v_is_approved, v_allocated_token
  FROM public."LLMUserPermission"
  WHERE "SerialNo" = p_serial_no AND "ProviderID" = v_provider_id;

  SELECT coalesce("TotalToken", 0) INTO v_quota_used
  FROM public."LLMUserQuota"
  WHERE "SerialNo" = p_serial_no AND "ProviderID" = v_provider_id AND "TargetMonth" = p_target_month;

  SELECT coalesce(jsonb_agg(jsonb_build_object('role', h."Role", 'content', h."Content") ORDER BY h."MessageID"), '[]'::jsonb)
  INTO v_history
  FROM (
    SELECT "MessageID", "Role", "Content"
    FROM public."ChatMessage"
    WHERE "SessionID" = v_session_id
      AND "Role" <> 'system'
      AND "MessageID" <> v_user_msg."MessageID"
    ORDER BY "MessageID" DESC
    LIMIT p_history_limit
  ) h;

  RETURN jsonb_build_object(
    'sessionId', v_session_id,
    'isNewSession', v_is_new,
    'title', v_title,
    'userMessage', to_jsonb(v_user_msg),
    'model', CASE WHEN v_model_id IS NULL THEN NULL ELSE jsonb_build_object(
      'modelId', v_model_id,
      'providerId', v_provider_id,
      'providerName', v_provider_name,
      'modelName', v_model_name,
      'modelDisplayName', v_model_display_name,
      'apiKey', v_api_key,
      'isActive', v_is_active
    ) END,
