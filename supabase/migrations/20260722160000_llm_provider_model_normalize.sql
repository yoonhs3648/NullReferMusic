-- LLM 스키마 정규화: LLMProvider(모델 목록, ApiKey 중복 보유) → LLMModel(모델) + LLMProvider(제공자, ApiKey 단독 보유)
--
-- 배경: 기존 "LLMProvider" 테이블은 사실 "모델" 목록이었고(Gemini 모델마다 행 하나),
-- 모든 행이 동일한 ApiKey를 그대로 복제해서 들고 있었다 — provider(ApiKey 소유자)와
-- model(그 provider가 제공하는 개별 모델)이 뒤섞여 있던 것. 이 마이그레이션은:
--
--   1) "LLMProvider"(기존, 모델 목록) → "LLMModel"로 이름 변경. PK "ProviderID" → "ModelID".
--      ApiKey/DailyLimit/MonthlyLimit/ProviderName 컬럼은 새 "LLMProvider"로 옮기거나
--      제거(정규화 — provider 단위 정보는 이제 join으로 가져온다). "ProviderID"(신규,
--      LLMProvider FK) 컬럼을 추가해 각 모델이 어느 provider 소속인지 표시.
--   2) 새 "LLMProvider" 테이블 생성: ProviderID(PK)/ProviderName/ApiKey/RegDate 만.
--      현재 유일한 provider(ProviderID=1, ProviderName='Google')를 기존 LLMModel.ApiKey
--      값으로 시드.
--   3) LLMUserPermission/LLMUserMonthlyAllocation/LLMUserQuota — 지금까지는 "모델별"
--      권한/할당/사용량이었는데, 요구사항상 이제 "provider별"이어야 한다. 기존
--      모델별 행들을 provider(현재는 전부 ProviderID=1)로 합친다(권한은 OR, 할당은
--      "무제한 있으면 무제한 우선, 아니면 최댓값", 사용량은 SUM).
--   4) LLMTokenHistory/ChatSession — ProviderID(제공자)뿐 아니라 ModelID(실제 사용
--      모델)도 함께 기록/저장하도록 컬럼 추가 + 기존 값 백필.
--   5) 위 구조 변경에 맞춰 관련 RPC를 다시 만든다:
--      - nrm_rpc_admin_replace_llm_providers(모델 시드) → nrm_rpc_admin_replace_llm_models
--      - nrm_rpc_chat_prepare_turn: p_provider_id(모델) → p_model_id, provider는 LLMModel
--        을 통해 join으로 얻는다. 제공자(모델) 단위 DailyLimit/MonthlyLimit 체크 로직은
--        완전히 제거(새 LLMProvider 스키마에 그 컬럼 자체가 없음 — 요구사항).
--      - nrm_rpc_chat_finalize_turn: p_model_id 파라미터 추가(LLMTokenHistory에 ModelID
--        같이 기록).
--
-- 상세 설계 근거는 docs/supabase-tables/llm.md 참고.

