/**
 * nrm-brand.config.json → Android strings.xml, NrmBrand.kt, (검증)
 * APK 빌드 전에 실행된다.
 */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const appRoot = path.resolve(__dirname, '..');

const configPath = path.join(appRoot, 'nrm-brand.config.json');
const raw = JSON.parse(fs.readFileSync(configPath, 'utf8'));

const displayName = String(raw.displayName ?? '').trim();
const storageFolderName = String(raw.storageFolderName ?? '').trim();
const serialNo = String(raw.serialNo ?? '').trim();
const userName = String(raw.userName ?? '').trim();

if (!displayName) {
  console.error('sync-nrm-brand: displayName is required in nrm-brand.config.json');
  process.exit(1);
}
if (!storageFolderName || /\s/.test(storageFolderName)) {
  console.error('sync-nrm-brand: storageFolderName must be non-empty without spaces');
  process.exit(1);
}

const stringsXml = `<?xml version="1.0" encoding="utf-8"?>
<resources>
  <string name="app_name">${escapeAndroidStringResource(displayName)}</string>
  <string name="nrm_bg_work_channel_name">백그라운드 작업</string>
  <string name="nrm_bg_work_channel_desc">다운로드·가사 생성이 백그라운드에서 계속 진행됩니다.</string>
  <string name="nrm_bg_work_notification_title">${escapeAndroidStringResource(`${displayName} — 작업 진행 중`)}</string>
  <string name="expo_splash_screen_resize_mode" translatable="false">contain</string>
  <string name="expo_splash_screen_status_bar_translucent" translatable="false">false</string>
</resources>
`;

const nrmBrandKt = `package com.nullrefer.music

/**
 * Auto-generated by app/scripts/sync-nrm-brand.mjs — do not edit by hand.
 * Source: app/nrm-brand.config.json
 */
object NrmBrand {
    const val DISPLAY_NAME: String = ${kotlinString(displayName)}
    const val STORAGE_FOLDER_NAME: String = ${kotlinString(storageFolderName)}
    /** Custom APK only — embedded for future licensing logic; not shown in version UI */
    const val SERIAL_NO: String = ${kotlinString(serialNo)}
    /** Custom APK only — inquiry registration; not shown in version UI */
    const val USER_NAME: String = ${kotlinString(userName)}
    val STORAGE_LOGS_PATH: String get() = "\$STORAGE_FOLDER_NAME/logs"
    fun userAgent(version: String): String = "\$STORAGE_FOLDER_NAME/\$version"
}
`;

const nrmBrandSwift = `// Auto-generated by app/scripts/sync-nrm-brand.mjs — do not edit by hand.
enum NrmBrand {
  static let storageFolderName = ${swiftString(storageFolderName)}
  static func userAgent(version: String) -> String {
    "\\(storageFolderName)/\\(version)"
  }
}
`;

const stringsPath = path.join(
  appRoot,
  'android/app/src/main/res/values/strings.xml',
);
const kotlinPath = path.join(
  appRoot,
  'android/app/src/main/java/com/nullrefer/music/NrmBrand.kt',
);
const swiftPath = path.join(
  appRoot,
  'modules/nrm-audio-metadata/ios/NrmBrand.generated.swift',
);
const buildGradlePath = path.join(appRoot, 'android/app/build.gradle');

fs.writeFileSync(stringsPath, stringsXml, 'utf8');
fs.writeFileSync(kotlinPath, nrmBrandKt, 'utf8');
fs.writeFileSync(swiftPath, nrmBrandSwift, 'utf8');

let gradle = fs.readFileSync(buildGradlePath, 'utf8');
const apkLine = `            outputFileName = findProperty('nrmApkVariant') == 'custom'
                ? "${storageFolderName}-custom-v\${variant.versionName}.apk"
                : "${storageFolderName}-v\${variant.versionName}.apk"`;
if (!gradle.includes('nrmApkVariant') || !gradle.includes(`${storageFolderName}-custom-v`)) {
  const replaced = gradle.replace(
    /outputFileName = findProperty\('nrmApkVariant'\)[\s\S]*?\.apk"/,
    apkLine.trim(),
  );
  if (replaced === gradle) {
    const legacy = gradle.replace(
      /outputFileName = "[^"]*\.apk"/,
      apkLine.trim(),
    );
    if (legacy === gradle) {
      console.error('sync-nrm-brand: could not patch android/app/build.gradle APK outputFileName');
      process.exit(1);
    }
    fs.writeFileSync(buildGradlePath, legacy, 'utf8');
  } else {
    fs.writeFileSync(buildGradlePath, replaced, 'utf8');
  }
}

console.log(`sync-nrm-brand: ok displayName="${displayName}" storageFolderName="${storageFolderName}"`);

function escapeAndroidStringResource(s) {
  let out = s
    .replace(/&/g, '&amp;')
    .replace(/</g, '&lt;')
    .replace(/>/g, '&gt;')
    .replace(/\\/g, '\\\\')
    .replace(/\n/g, '\\n')
    .replace(/\r/g, '\\r')
    .replace(/\t/g, '\\t');
  // Android strings.xml: 본문에 ' 가 있으면 \"...\" 로 감싸거나 \' 로 이스케이프해야 AAPT2 통과
  if (out.includes("'")) {
    out = out.replace(/"/g, '\\"');
    return `"${out}"`;
  }
  return out;
}

function escapeXml(s) {
  return s
    .replace(/&/g, '&amp;')
    .replace(/</g, '&lt;')
    .replace(/>/g, '&gt;')
    .replace(/"/g, '&quot;');
}

function kotlinString(s) {
  return `"${s.replace(/\\/g, '\\\\').replace(/"/g, '\\"')}"`;
}

function swiftString(s) {
  return `"${s.replace(/\\/g, '\\\\').replace(/"/g, '\\"')}"`;
}
